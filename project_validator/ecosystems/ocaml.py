"""OCaml: built with dune and packaged for opam, judged by the OCaml compiler versions CI runs and by what dune's
profile does to the compiler's warnings.

dune's `dev` profile (the default) builds with a strict warning set and makes those warnings errors; its `release`
profile (`--profile release`, `--release`, `-p`) turns both off. So the warning practices ask that CI build and test in
the dev profile, and that no dune file's `(flags …)` field drops `:standard`, which is where the profile's flags come
from, or turns the warnings off again (`-w -a`, `-warn-error -a`). The dune files are read for their forms, not parsed
as a whole."""

