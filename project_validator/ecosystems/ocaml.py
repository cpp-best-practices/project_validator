# --- Recognition and toolchains -------------------------------------------------------------------------------------

# ocaml/setup-ocaml's `ocaml-compiler`: a version (`5.2`, `4.14.x`) or a package (`ocaml-base-compiler.5.2.0`,
# `ocaml-variants.5.2.0+options`); the ocaml/opam images are tagged `<distro>-ocaml-<version>`.
_OCAML_VERSION = r"(\d+\.\d+(?:\.(?:\d+|x))?)"

OCAML_ECOSYSTEM = Ecosystem(
    label="OCaml",
    languages=OCAML,
    build_systems=(DUNE, OPAM),
    source_suffixes={".ml": "OCaml", ".mli": "OCaml"},
    # ocamllex and Menhir grammars and Eliom modules are OCaml once the project is; cram tests (`.t`) and odoc pages
    # (`.mld`) are files of the ecosystem with no language of their own.
    ambiguous_suffixes={
        ".mll": "OCaml",
        ".mly": "OCaml",
        ".eliom": "OCaml",
        ".eliomi": "OCaml",
        ".t": None,
        ".mld": None,
    },
    toolchain=toolchain_patterns(
        "OCaml",
        version=_OCAML_VERSION,
        inputs=("ocaml-compiler", "ocaml-version"),
        more=(
            rf"\bocaml/opam:[\w.-]*?ocaml-{_OCAML_VERSION}",
            rf"\bocaml-(?:base-compiler|variants|system)\.{_OCAML_VERSION}",
            rf"\bopam\s+switch\s+create\s+(?:\S+\s+)?(?:--packages=)?(?:ocaml\.)?{_OCAML_VERSION}(?!\S)",
        ),
        commands=r"\bdune\b|\bopam\b|\bocaml(?:c|opt|find|lex|dep|build)?\b|\bocamlformat\b|\bmenhir\b",
        setup=("ocaml",),
    ),
)

OCAML_VERSIONS = versions_axis("OCaml version", "OCaml", OCAML)
