OCAML = frozenset({"OCaml"})
DUNE_PROJECT = "dune-project"
DUNE_FILES = (DUNE_PROJECT, "dune", "dune-workspace")


def _is_build_tree(directory: Path) -> bool:
    """dune builds in `_build` beside `dune-project`; `_opam` is a local opam switch (`opam switch create .`)."""
    beside = directory.name == "_build" and (directory.parent / DUNE_PROJECT).is_file()
    return beside or (directory.name == "_opam" and (directory / ".opam-switch").is_dir())


DUNE = BuildSystem(name="dune", files=DUNE_FILES, languages=OCAML, is_build_tree=_is_build_tree)
# A package description, generated by dune from `dune-project` or written by hand (`opam` in older projects).
OPAM = BuildSystem(name="opam", files=("*.opam", "opam"), languages=OCAML)

# `opam exec -- dune build` runs dune in the switch.
OPAM_EXEC = launcher("opam exec", (("opam", "exec"),), with_values=frozenset({"--switch", "--root"}))


# --- dune commands --------------------------------------------------------------------------------------------------

# The subcommands that build (and so compile with the profile's flags).
_DUNE_BUILDS = frozenset({"build", "test", "runtest", "exec", "install", "fmt"})
_RUNTEST_ALIAS = re.compile(r"@@?(?:[\w./-]+/)?runtest")
_FMT_ALIAS = re.compile(r"@@?(?:[\w./-]+/)?fmt")


def dune_subcommand(command: Command) -> str | None:
    """The subcommand of a dune command (`build`, `test`); None for a command that is not dune's."""
    argv = resolved(command)
    return argv[1] if program(argv) == "dune" and len(argv) > 1 else None


def dune_profile(command: Command) -> str | None:
    """The profile a dune command builds with: `--profile`, or release with `--release` or `-p` (a release build of
    the packages named), or `DUNE_PROFILE` in its environment, or dev. None for a command that is not dune's."""
    if dune_subcommand(command) is None:
        return None
    argv = resolved(command)
    if has_option(argv, "--release", "-p", "--for-release-of-packages"):
        return "release"
    profiles = option_values(argv, "--profile")
    return profiles[-1] if profiles else command.env.get("DUNE_PROFILE", "dev")


def _builds_alias(command: Command, alias: re.Pattern[str]) -> bool:
    return dune_subcommand(command) == "build" and any(alias.fullmatch(word) for word in resolved(command)[2:])


def _runs_tests(command: Command) -> bool:
    return dune_subcommand(command) in ("test", "runtest") or _builds_alias(command, _RUNTEST_ALIAS)


# --- The forms of a dune file ----------------------------------------------------------------------------------------

_COMMENT = re.compile(r";[^\n]*")


def _spans(text: str, name: str) -> Iterator[tuple[int, int, int]]:
    """(start, end of the head, end) of each `(name …)` form in `text`, nested forms included."""
    for match in re.finditer(rf"\({re.escape(name)}(?=[\s()])", text):
        depth = 0
        for index in range(match.start(), len(text)):
            depth += {"(": 1, ")": -1}.get(text[index], 0)
            if depth == 0:
                yield match.start(), match.end(), index
                break


def forms(text: str, name: str) -> tuple[str, ...]:
    """What each `(name …)` form of a dune file holds, as text (`(test (name t))` holds `(name t)`); comments are
    dropped, and strings are not told apart."""
    text = _COMMENT.sub("", text)
    return tuple(text[head:end].strip() for _, head, end in _spans(text, name))


def _without(text: str, name: str) -> str:
    """`text` without its `(name …)` forms."""
    kept, position = [], 0
    for start, _, end in _spans(text, name):
        if start >= position:
            kept.append(text[position:start])
            position = end + 1
    return "".join((*kept, text[position:]))


# --- Tests and coverage ---------------------------------------------------------------------------------------------

_NAMES = re.compile(r"\(names?\s+([^()]*)\)")
DUNE_TESTS = "dune tests"


def _read_tests(path: str, text: str) -> Iterator[Setting]:
    """The tests a dune file declares: `test` and `tests` stanzas (by name), a library's `inline_tests` (ppx_expect,
    ppx_inline_test) and `cram` tests."""
    for kind in ("test", "tests"):
        for found in forms(text, kind):
            names = [name for match in _NAMES.finditer(found) for name in match[1].split()]
            yield from settings(DUNE_TESTS, path, ((kind, name) for name in names or ["?"]), heuristic=True)
    for kind in ("inline_tests", "cram"):
        yield from settings(DUNE_TESTS, path, ((kind, True) for _ in forms(text, kind)), heuristic=True)


DUNE_TEST_STANZAS = SettingsReader(name=DUNE_TESTS, files=("dune",), read=_read_tests)

DUNE_TEST = test_runner(
    name="dune test",
    languages=OCAML,
    how="dune test (or dune runtest, dune build @runtest)",
    runs=lambda command, _facts: tested() if _runs_tests(command) else None,
    tests=Definition(
        found=lambda facts: (setting.path for setting in facts.settings(DUNE_TESTS)),
        default=False,
        describe="test stanzas, inline_tests or cram tests in dune files",
        from_test_units=True,
    ),
    reads=(DUNE_TESTS,),
)


def _bisect(command: Command, _facts: Facts) -> Run | None:
    """bisect_ppx instruments every branch point: a dune build or test run `--instrument-with bisect_ppx` (or with
    `BISECT_ENABLE`, the older way), or `bisect-ppx-report`, which writes the report."""
    argv = resolved(command)
    if program(argv) == "bisect-ppx-report":
        return measured(Granularity.BRANCH)
    if dune_subcommand(command) not in _DUNE_BUILDS:
        return None
    backends = {backend for value in option_values(argv, "--instrument-with") for backend in value.split(",")}
    enabled = command.env.get("BISECT_ENABLE", "").lower() in ("yes", "true", "1")
    return measured(Granularity.BRANCH) if "bisect_ppx" in backends or enabled else None


BISECT_PPX = coverage_tool(
    name="bisect_ppx",
    languages=OCAML,
    can={Granularity.BRANCH: "dune test --instrument-with bisect_ppx, then bisect-ppx-report"},
    measures=_bisect,
)


# --- Formatting -----------------------------------------------------------------------------------------------------

OCAMLFORMAT_SETTINGS = file_reader("ocamlformat", (".ocamlformat",))


def _dune_fmt(command: Command, facts: Facts) -> Run | None:
    """`dune build @fmt` fails on a file ocamlformat would change (with `--auto-promote`, it rewrites it instead);
    `dune fmt` rewrites."""
    if dune_subcommand(command) == "fmt":
        return formatted(command, facts, checks=False)
    if not _builds_alias(command, _FMT_ALIAS):
        return None
    return formatted(command, facts, checks=not has_option(resolved(command), "--auto-promote"))


# ocamlformat refuses to run without a `.ocamlformat` naming its version: the style is never a default.
OCAMLFORMAT = format_tool(
    name="ocamlformat",
    languages=OCAML,
    can={Enforcement.CHECK: "dune build @fmt (or ocamlformat --check)", Enforcement.APPLY: "dune fmt"},
    formats=either(_dune_fmt, flagged(("ocamlformat",), checks=("--check",), applies=("-i", "--inplace"))),
    style=defined_by(files=(OCAMLFORMAT_SETTINGS.name,), default=False),
)


# --- Warnings -------------------------------------------------------------------------------------------------------

_FLAGS = "flags"


def _read_flags(path: str, text: str) -> Iterator[Setting]:
    """Each `(flags …)` field of a dune file, outside its `(release …)` environment, which the dev profile does not
    read."""
    fields = forms(_without(_COMMENT.sub("", text), "release"), _FLAGS)
    return settings("dune", path, ((_FLAGS, " ".join(field.split())) for field in fields), heuristic=True)


DUNE_FLAGS = SettingsReader(name="dune", files=DUNE_FILES, read=_read_flags)


def _drops(flags: str, options: tuple[str, ...]) -> bool:
    """Whether a `flags` field drops the dev profile's warnings: it leaves out `:standard`, which is where they come
    from, or turns them off again with one of `options` followed by `-a` (`-w -a`, `-warn-error -a`)."""
    words = flags.replace("(", " ").replace(")", " ").split()
    dropped = any(word in options and after.startswith("-a") for word, after in pairwise(words))
    return ":standard" not in words or dropped


def _dev_profile(*options: str) -> Found:
    """The dune commands that build in the dev profile, unless a dune file's flags drop what the profile sets."""

    def found(facts: Facts, _compiler: str | None) -> Iterator[Evidence]:
        if any(_drops(str(setting.value), options) for setting in facts.where(Setting, tool="dune", key=_FLAGS)):
            return
        for command in facts.of(Command):
            if dune_profile(command) == "dev" and dune_subcommand(command) in _DUNE_BUILDS:
                yield Evidence(f"CI ({command.origin.path}: dune's dev profile)")

    return found


_SEARCHED = "CI configuration and the dune files"
WARNINGS = Practice(
    name=PracticeName.WARNINGS,
    languages=OCAML,
    requirements=always(
        Requirement(
            name="dune's dev profile warning set (or -w +a)",
            runs=re.compile(r"(?<![\w-])-w\s+[+@]a(?![\w])"),
            found=_dev_profile("-w"),
        )
    ),
    reads=("dune",),
    words=Wording(
        kind="OCaml warning settings",
        searched=_SEARCHED,
        hint="build and test in dune's dev profile in CI (no --profile release or -p), and keep :standard in every "
        "(flags …) field",
    ),
)
WARNINGS_AS_ERRORS = Practice(
    name=PracticeName.WARNINGS_AS_ERRORS,
    languages=OCAML,
    requirements=always(
        Requirement(
            name="dune's dev profile (or -warn-error +a)",
            runs=re.compile(r"(?<![\w-])(?:-warn-error\s+\+a|-w\s+@a)(?![\w])"),
            found=_dev_profile("-w", "-warn-error"),
        )
    ),
    any_one=True,
    reads=("dune",),
    words=Wording(
        kind="warnings as errors",
        searched=_SEARCHED,
        hint="build and test in dune's dev profile in CI, which makes its warnings errors (the release profile does "
        "not), and keep :standard in every (flags …) field",
    ),
)

