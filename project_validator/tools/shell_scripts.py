"""Shell scripts of the project that CI runs (`ci/lint.sh`, `bash scripts/check.sh`): the commands they run in turn.

A script runs where the command that runs it does; its arguments (`$1`) are not known. Shell functions it defines
are not followed: their bodies are split like any other lines.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from project_validator.core import Context
from project_validator.facts import Command, Origin, Unknown, resolved
from project_validator.facts.arguments import positional, program
from project_validator.facts.expansion import CommandExpander, Expansion, Script, joined

SHELLS = frozenset({"sh", "bash", "zsh", "dash", "ksh"})
# Shell options that take a value (`bash -o pipefail script.sh`).
_SHELL_VALUES = frozenset({"-o", "+o", "-O", "+O"})
# `#!/bin/bash`, `#!/usr/bin/env bash`, `#!/usr/bin/env -S bash -e`: the interpreter's name, wherever it is.
_SHEBANG = re.compile(r"\A#!\s*(?:/usr/bin/env\s+(?:-S\s+)?)?(?:\S*/)?(?P<name>[\w.-]+)")


def interpreter(text: str) -> str | None:
    """The program a script's shebang names (`bash` for `#!/usr/bin/env bash`); None for a file without one."""
    match = _SHEBANG.match(text)
    return match["name"] if match else None


def _script(command: Command) -> str | None:
    """The script file a command runs: `sh script.sh` (not `sh -c '…'`), `./script.sh` run directly, or a script
    the shell sources (`. ci/env.sh`, `source ci/env.sh`)."""
    argv = resolved(command)
    if argv[:1] in ((".",), ("source",)):
        return argv[1] if len(argv) > 1 else None
    if program(argv) in SHELLS:
        words, _ = positional(argv, _SHELL_VALUES)
        return None if "-c" in argv[1:] or not words else words[0]
    return argv[0] if argv and ("/" in argv[0] or argv[0].endswith(".sh")) else None


# Scripts that are not shell to read: a launcher with an archive after its shebang (scalafmt's, metals'), and the
# configure script autoconf generates (opam's), which runs no tool of the project's.
_GENERATED = re.compile(r"^#[^\n]*Generated by GNU Autoconf", re.MULTILINE)


def _is_shell_script(text: str, path: str) -> bool:
    readable = "\0" not in text[:65536] and not _GENERATED.search(text[:4096])
    return readable and (path.endswith(".sh") or interpreter(text) in SHELLS)


def _shell_script(command: Command, context: Context) -> list[Expansion] | None:
    path = _script(command)
    if path is None or path.startswith(("/", "$", "~", ":")) or any(character in path for character in " \t\n*?["):
        return None  # elsewhere, a pattern, or a whole command line quoted as one word (`"bash -x ./ci/test.sh"`)
    found = joined(command.directory, path.removeprefix("./"))
    if not context.project.exists(found):
        # A program the build makes (`./build/app`) is not in the repository either; a shell script is written by CI.
        return [_missing(command, found)] if found.endswith((".sh", ".bash")) else None
    if not _is_shell_script(text := context.project.read_text(found), found):
        return None
    return [Script(text=text, origin=Origin(path=str(PurePosixPath(found))), whole=True)]


def _missing(command: Command, path: str) -> Unknown:
    reason = "it is not in the repository: a step before writes or downloads it, or it is missing"
    return Unknown(origin=command.origin, subject=f"the script {path}", reason=reason)


SHELL_SCRIPTS = CommandExpander(name="shell scripts", expand=_shell_script)
