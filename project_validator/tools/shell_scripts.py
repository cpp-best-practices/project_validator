"""Shell scripts of the project that CI runs (`ci/lint.sh`, `bash scripts/check.sh`, `scripts\\build.bat`,
`pwsh -File ci/test.ps1`): the commands they run in turn, each read in the dialect of the shell that runs it (see
`project_validator.facts.shell`).

A script runs where the command that runs it does; its arguments (`$1`, `%1`) are not known. Shell functions it
defines are not followed: their bodies are split like any other lines.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from project_validator.core import Context
from project_validator.facts import Command, Origin, Unknown, resolved
from project_validator.facts.arguments import positional, program
from project_validator.facts.exit_status import Shell, shell_of
from project_validator.facts.expansion import CommandExpander, Expansion, Script, joined
from project_validator.facts.shell import CMD, POSIX, POWERSHELL, Dialect

SHELLS = frozenset({"sh", "bash", "zsh", "dash", "ksh"})
# Shell options that take a value (`bash -o pipefail script.sh`).
_SHELL_VALUES = frozenset({"-o", "+o", "-O", "+O"})
# `#!/bin/bash`, `#!/usr/bin/env bash`, `#!/usr/bin/env -S bash -e`: the interpreter's name, wherever it is.
_SHEBANG = re.compile(r"\A#!\s*(?:/usr/bin/env\s+(?:-S\s+)?)?(?:\S*/)?(?P<name>[\w.-]+)")


def interpreter(text: str) -> str | None:
    """The program a script's shebang names (`bash` for `#!/usr/bin/env bash`); None for a file without one."""
    match = _SHEBANG.match(text)
    return match["name"] if match else None


# The suffixes of the scripts other shells run, and how each is read.
_SUFFIXES = {".bat": CMD, ".cmd": CMD, ".ps1": POWERSHELL}
# PowerShell's options that take a value, and the one that names a script file to run.
_POWERSHELL_VALUES = frozenset({"-File", "-f", "-ExecutionPolicy", "-ep", "-Command", "-c"})


def _script(command: Command) -> tuple[str, Dialect] | None:
    """The script file a command runs, and how it is read: `sh script.sh` (not `sh -c '…'`), `./script.sh` run
    directly, or a script the shell sources (`. ci/env.sh`, `source ci/env.sh`); a batch file (`scripts\\build.bat`,
    `cmd /c build.bat`), or a PowerShell script (`./ci/test.ps1`, `pwsh -File ci/test.ps1`)."""
    argv = resolved(command)
    if argv[:1] in ((".",), ("source",)):
        return (argv[1], POSIX) if len(argv) > 1 else None
    if program(argv) in (*SHELLS, "cmd", "pwsh", "powershell"):
        return _run_by_shell(argv)
    if argv and (suffixed := _suffixed(argv[0])) is not None:
        return suffixed
    return (argv[0], POSIX) if argv and ("/" in argv[0] or argv[0].endswith(".sh")) else None


def _run_by_shell(argv: tuple[str, ...]) -> tuple[str, Dialect] | None:
    """The script a shell runs: `bash script.sh` (not `bash -c '…'`), `cmd /c build.bat`, `pwsh -File test.ps1`."""
    name = program(argv)
    if name == "cmd":
        rest = [word for word in argv[1:] if word.lower() not in ("/c", "/k", "/d", "/q", "/s")]
        return _suffixed(rest[0]) if rest and any(word.lower() in ("/c", "/k") for word in argv[1:]) else None
    if name in ("pwsh", "powershell"):
        found = _powershell_file(argv)
        return None if found is None else (found, POWERSHELL)
    words, _ = positional(argv, _SHELL_VALUES)
    return None if "-c" in argv[1:] or not words else (words[0], POSIX)


def _suffixed(word: str) -> tuple[str, Dialect] | None:
    """A batch file or a PowerShell script by its suffix, its path written with slashes (`scripts\\build.bat`)."""
    dialect = next((found for suffix, found in _SUFFIXES.items() if word.lower().endswith(suffix)), None)
    return None if dialect is None else (word.replace("\\", "/"), dialect)


def _powershell_file(argv: tuple[str, ...]) -> str | None:
    """The script `pwsh -File script.ps1` (or `pwsh script.ps1`) runs; None for `pwsh -Command …`."""
    for index, word in enumerate(argv[1:], start=1):
        if word in ("-File", "-f") and index + 1 < len(argv):
            return argv[index + 1].replace("\\", "/")
    words, _ = positional(argv, _POWERSHELL_VALUES)
    command = any(word in ("-Command", "-c") for word in argv[1:])
    return words[0].replace("\\", "/") if words and not command and words[0].lower().endswith(".ps1") else None


# Scripts that are not shell to read: a launcher with an archive after its shebang (scalafmt's, metals'), and the
# configure script autoconf generates (opam's), which runs no tool of the project's.
_GENERATED = re.compile(r"^#[^\n]*Generated by GNU Autoconf", re.MULTILINE)


def _is_shell_script(text: str, path: str, dialect: Dialect) -> bool:
    readable = "\0" not in text[:65536] and not _GENERATED.search(text[:4096])
    return readable and (dialect is not POSIX or path.endswith(".sh") or interpreter(text) in SHELLS)


def _shell_script(command: Command, context: Context) -> list[Expansion] | None:
    if (found_script := _script(command)) is None:
        return None
    path, dialect = found_script
    if path.startswith(("/", "$", "~")) or any(character in path for character in " \t\n*?[%:"):
        # Elsewhere (`C:/BuildTools/vcvars64.bat` too), a pattern, or a whole command line quoted as one word
        # (`"bash -x ./ci/test.sh"`).
        return None
    found = joined(command.directory, path.removeprefix("./"))
    if not context.project.exists(found):
        # A program the build makes (`./build/app`) is not in the repository either; a shell script is written by CI.
        # A batch file or PowerShell script most often is a program (`npm.cmd`) or generated (`vendor/bin/x.bat`).
        return [_missing(command, found)] if dialect is POSIX and found.endswith((".sh", ".bash")) else None
    if not _is_shell_script(text := context.project.read_text(found), found, dialect):
        return None
    origin = Origin(path=str(PurePosixPath(found)))
    shell = _shell(resolved(command), text) if dialect is POSIX else None
    return [Script(text=text, origin=origin, whole=True, shell=shell, dialect=dialect)]


def _shell(argv: tuple[str, ...], text: str) -> Shell | None:
    """The options the shell that runs a script starts with: those of the shell command that runs it (`bash -e
    ci/lint.sh`), or of its shebang when it runs itself; None for a script sourced into a shell not seen."""
    if argv[:1] in ((".",), ("source",)):
        return None
    if program(argv) in SHELLS:
        return shell_of(" ".join(argv))
    shebang = text.partition("\n")[0].removeprefix("#!").split() if text.startswith("#!") else ["sh"]
    if shebang and PurePosixPath(shebang[0]).name == "env":
        shebang = [word for word in shebang[1:] if word != "-S"]
    return shell_of(" ".join(shebang))


def _missing(command: Command, path: str) -> Unknown:
    reason = "it is not in the repository: a step before writes or downloads it, or it is missing"
    return Unknown(origin=command.origin, subject=f"the script {path}", reason=reason)


SHELL_SCRIPTS = CommandExpander(name="shell scripts", expand=_shell_script)


def _command_string(command: Command, _context: Context) -> list[Expansion] | None:
    """`bash -c 'cd test && go test ./...'`: the commands of the string a POSIX shell runs, with the options before
    it its own (`bash -ec '…'`, `sh -o pipefail -c '…'`)."""
    argv = resolved(command)
    if program(argv) not in SHELLS:
        return None
    words = iter(enumerate(argv[1:], start=1))
    for index, word in words:
        if word in _SHELL_VALUES:
            next(words, None)
        elif word.startswith("-") and not word.startswith("--") and "c" in word[1:]:
            if index + 1 >= len(argv):
                return None
            shell = shell_of(" ".join(argv[: index + 1]))
            return [Script(text=argv[index + 1], origin=command.origin, shell=shell, inline=True)]
        elif not word.startswith(("-", "+")):
            return None
    return None


SHELL_COMMAND_STRINGS = CommandExpander(name="shell command strings", expand=_command_string)
